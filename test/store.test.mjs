import test from 'node:test'
import assert from 'node:assert/strict'
import { mkdtemp, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { openStore } from '../dsh/store.js'

const tinyJpeg = Buffer.from('ffd8ffc0000b080001000103011100021101031101ffd9', 'hex')

test('creates a patient and exposes an empty dashboard', async () => {
  const root = await mkdtemp(join(tmpdir(), 'xyb-workbench-'))
  const store = await openStore(root)
  const patient = store.createPatient({ displayName: '测试患者', heightCm: 165 })
  assert.equal(store.listPatients().length, 1)
  assert.equal(store.dashboard(patient.id).patient.displayName, '测试患者')
  assert.deepEqual(store.dashboard(patient.id).latestObservations, [])
  store.addObservation({ patientId: patient.id, metricCode: 'CA19-9', valueNum: 120, valueRaw: '120', unitRaw: 'U/mL', occurredAt: '2026-10-01' })
  store.addObservation({ patientId: patient.id, metricCode: 'CA19-9', valueNum: 98, valueRaw: '98', unitRaw: 'U/mL', occurredAt: '2026-10-10' })
  const metric = store.dashboard(patient.id).latestObservations[0]
  assert.equal(metric.metricCode, 'CA19-9')
  assert.equal(metric.valueNum, 98)
  assert.equal(metric.delta, -22)
  assert.deepEqual(store.observationHistory(patient.id).map((entry) => entry.valueNum), [120, 98])
  const document = await store.importDocument({ patientId: patient.id, title: '血检报告', kindCode: 'lab', fileName: 'lab.txt', reportedAt: '2026-10-10' }, Buffer.from('2026-10-10\nCA19-9: 100 U/mL\nCEA: 4.2 ng/mL'))
  assert.equal(document.parseStatus, 'pending')
  assert.equal(store.db.prepare('SELECT file_rel_path AS path FROM document WHERE id = ?').get(document.id).path.startsWith(`input/documents/${patient.id}/`), true)
  assert.equal((await store.readDocument(document.id)).bytes.toString('utf8').includes('CA19-9'), true)
  const parse = await store.parseDocument(document.id)
  assert.equal(parse.candidateCount, 2)
  const candidates = store.listCandidates(patient.id, document.id)
  const ca199 = candidates.find((candidate) => candidate.payload.metricCode === 'CA19-9')
  assert.equal(ca199.payload.valueNum, 100)
  store.confirmCandidate(ca199.id)
  assert.equal(store.listCandidates(patient.id, document.id).find((candidate) => candidate.id === ca199.id).status, 'confirmed')
  const csv = await store.importDocument({ patientId: patient.id, title: '指标.csv', kindCode: 'lab', fileName: 'markers.csv' }, Buffer.from('日期,项目,结果,单位\n2026-10-11,CA19-9,88,U/mL\n2026-10-11,CEA,4.2,ng/mL'))
  const csvParse = await store.parseDocument(csv.id)
  assert.equal(csvParse.candidateCount, 2, 'CSV headers map dates, metric codes, values, and units into review candidates')
  assert.deepEqual(store.listCandidates(patient.id, csv.id).map((candidate) => candidate.payload.metricCode).sort(), ['CA19-9', 'CEA'])
  assert.match((await store.readExtractionResult(csv.id)).markdown, /2026-10-11,CA19-9,88/u, 'CSV source is available in the in-app parsed-content view')
  const pdf = await store.importDocument({ patientId: patient.id, title: '扫描报告.pdf', kindCode: 'other', fileName: 'scan.pdf' }, Buffer.from('%PDF demo'))
  const mineruParse = await store.parseDocument(pdf.id, { mineru: async () => ({ markdown: '2026-10-12\nCA19-9: 72 U/mL', engine: 'mineru-flash' }) })
  assert.equal(mineruParse.candidateCount, 1)
  assert.match((await store.readExtractionResult(pdf.id)).markdown, /CA19-9: 72/u, 'MinerU markdown remains available for document review')
  const documentPath = store.db.prepare('SELECT file_rel_path AS path FROM document WHERE id = ?').get(document.id).path
  store.db.prepare('UPDATE document SET file_rel_path = ? WHERE id = ?').run('../../outside.txt', document.id)
  await assert.rejects(store.readDocument(document.id), /路径无效/u)
  store.db.prepare('UPDATE document SET file_rel_path = ? WHERE id = ?').run(documentPath, document.id)
  store.addAppointment({ patientId: patient.id, kindCode: 'chemotherapy', scheduledAt: '2026-10-20T09:00:00', organization: '肿瘤科' })
  assert.equal(store.dashboard(patient.id).upcomingAppointments[0].kindCode, 'chemotherapy')
  const cyclePlan = store.createTreatmentCyclePlan({ patientId: patient.id, regimen: 'mFOLFIRINOX', firstAt: '2026-10-20T09:00', cycleDays: 14, cycleCount: 2, bloodTestLeadDays: 3, ctIntervalDays: 90, ctCount: 1 })
  assert.equal(cyclePlan.appointments.filter((item) => item.kindCode === 'chemotherapy').length, 2)
  assert.equal(store.listTreatmentCyclePlans(patient.id)[0].events.length, 2)
  assert.equal(store.db.prepare("SELECT COUNT(*) AS count FROM reminder WHERE rule_code = 'blood-test-before-chemotherapy'").get().count, 2)
  const chemoEvent = store.listTreatmentCyclePlans(patient.id)[0].events[0]
  assert.equal(store.db.prepare("SELECT related_treatment_event_id FROM appointment WHERE kind_code = 'chemotherapy' AND related_plan_id = ? ORDER BY scheduled_at LIMIT 1").get(cyclePlan.id).related_treatment_event_id, chemoEvent.id)
  assert.equal(store.db.prepare("SELECT related_treatment_event_id FROM appointment WHERE kind_code = 'blood-test' AND related_plan_id = ? ORDER BY scheduled_at LIMIT 1").get(cyclePlan.id).related_treatment_event_id, chemoEvent.id)
  const task = store.createAgentTask({ patientId: patient.id, pageCode: 'dashboard', agentRoleCode: 'pancreatic-care-manager', promptRendered: '请基于已确认记录整理问题。', inputSnapshot: { metrics: 3 } })
  assert.equal(task.status, 'queued')
  assert.equal(store.attachAgentTaskSession(task.id, 'session-001').sessionRef, 'session-001')
  store.addNutritionEntry({ patientId: patient.id, occurredAt: '2026-10-12', weightKg: 56.2, intakeKcal: 1450, proteinG: 65 })
  store.addNutritionProductUsage({ patientId: patient.id, occurredAt: '2026-10-12', productName: '营养制剂示例', volumeMl: 200, energyKcal: 300, proteinG: 12 })
  assert.equal(store.nutritionSummary(patient.id).latest.bmi, 20.6)
  assert.equal(store.nutritionSummary(patient.id).products[0].productName, '营养制剂示例')
  store.addSymptomRecord({ patientId: patient.id, symptomCode: '腹胀', severity: '轻微', onsetAt: '2026-10-12', note: '饭后出现' })
  assert.equal(store.listSymptomRecords(patient.id)[0].symptomCode, '腹胀')
  store.addCareRecord({ patientId: patient.id, type: 'toxicity', toxicityCode: '手足麻木', onsetAt: '2026-10-12', ctcaeGrade: '1', status: 'active' })
  store.addCareRecord({ patientId: patient.id, type: 'comorbidity', comorbidityCode: '胆道梗阻', occurredAt: '2026-10-12', state: 'active' })
  const peiMedication = store.addCareRecord({ patientId: patient.id, type: 'medication', drugCode: '胰酶制剂', purposeCode: '按处方', doseText: '按医嘱', startedAt: '2026-10-12' })
  store.addCareRecord({ patientId: patient.id, type: 'catheter', typeCode: 'Port', implantDate: '2026-09-01', site: '胸前', status: 'in_place' })
  assert.equal(store.listCareRecords(patient.id).toxicities[0].toxicityCode, '手足麻木')
  assert.equal(store.listCareRecords(patient.id).comorbidities[0].comorbidityCode, '胆道梗阻')
  assert.equal(store.listCareRecords(patient.id).medications[0].drugCode, '胰酶制剂')
  assert.equal(store.listCareRecords(patient.id).catheters[0].typeCode, 'Port')
  store.addCareRecord({ patientId: patient.id, type: 'catheter-maintenance', catheterId: store.listCareRecords(patient.id).catheters[0].id, date: '2026-10-13', action: '维护记录', abnormal: false, nextPlannedDate: '2026-11-13' })
  store.addCareRecord({ patientId: patient.id, type: 'medication-status', medicationId: peiMedication.id, status: 'stopped' })
  assert.equal(store.listCareRecords(patient.id).catheters[0].maintenance[0].action, '维护记录')
  assert.equal(store.listCareRecords(patient.id).medications[0].status, 'stopped')
  store.addPeiRecord({ patientId: patient.id, occurredAt: '2026-10-13', medicationRecordId: peiMedication.id, withMeal: 'yes', doseText: '医嘱剂量', stoolChangeCode: '无明显变化' })
  assert.equal(store.nutritionSummary(patient.id).peiRecords[0].medicationName, '胰酶制剂')
  store.addMoodCheckin({ patientId: patient.id, mood: '有些担心', occurredAt: '2026-10-12', note: '今天愿意记录的内容' })
  assert.equal(store.listMoodCheckins(patient.id)[0].mood, '有些担心')
  store.addMolecularResult({ patientId: patient.id, assayType: 'NGS', markerCode: 'KRAS', geneCode: 'KRAS', resultType: 'positive', resultRaw: 'G12D', alterationCode: '错义变异', vafPct: 18.4, occurredAt: '2026-10-12', testMethod: 'NGS' })
  store.addMolecularResult({ patientId: patient.id, assayType: 'IHC', markerCode: 'CLDN18.2', resultType: 'positive', resultRaw: '阳性 3+', intensity: '3+', positivePct: 80, occurredAt: '2026-10-13', testMethod: 'IHC' })
  assert.equal(store.listMolecularResults(patient.id).length, 2)
  assert.equal(store.listMolecularResults(patient.id)[1].vafPct, 18.4)
  assert.equal(store.listMolecularResults(patient.id)[0].markerCode, 'CLDN18.2')
  const bookmark = store.saveTrialBookmark({ patientId: patient.id, trialKey: 'CTR20260001', note: '与医生讨论' })
  assert.equal(bookmark.state, 'saved')
  assert.equal(store.listTrialBookmarks(patient.id)[0].trialKey, 'CTR20260001')
  const subscription = store.createTrialSubscription({ patientId: patient.id, queryText: 'KRAS G12D', targetTerms: ['KRAS', 'G12D'] })
  assert.deepEqual(subscription.targetTerms, ['KRAS', 'G12D'])
  assert.equal(store.listTrialSubscriptions(patient.id)[0].queryText, 'KRAS G12D')
  const artifact = await store.exportPatientReport(patient.id)
  assert.equal(artifact.fileRelPath.startsWith(`output/reports/${patient.id}/`), true)
  assert.match(await readFile(join(root, artifact.fileRelPath), 'utf8'), /CA19-9/u)
  assert.equal(store.db.prepare('SELECT COUNT(*) AS count FROM export_artifact').get().count, 1)
  const markdownArtifact = await store.exportPatientReport(patient.id, 'md')
  assert.match(await readFile(join(root, markdownArtifact.fileRelPath), 'utf8'), /CA19-9/u)
  const docxArtifact = await store.exportPatientReport(patient.id, 'docx')
  assert.equal((await readFile(join(root, docxArtifact.fileRelPath))).subarray(0, 2).toString(), 'PK')
  const jpegArtifact = await store.saveJpegReport(patient.id, `data:image/jpeg;base64,${Buffer.from([0xff, 0xd8, 0xff, 0xd9]).toString('base64')}`)
  assert.equal((await readFile(join(root, jpegArtifact.fileRelPath))).subarray(0, 3).toString('hex'), 'ffd8ff')
  const pdfArtifact = await store.saveVisualReport(patient.id, `data:image/jpeg;base64,${tinyJpeg.toString('base64')}`, 'pdf')
  const pdfBytes = await readFile(join(root, pdfArtifact.fileRelPath))
  assert.equal(pdfArtifact.formatCode, 'pdf')
  assert.match(pdfArtifact.fileRelPath, /\.pdf$/u)
  assert.equal(pdfBytes.subarray(0, 8).toString(), '%PDF-1.4')
  assert.match(pdfBytes.toString('latin1'), /\/Subtype \/Image/u)
  assert.match(pdfBytes.toString('latin1'), /\/Filter \/DCTDecode/u)
  const supportResources = store.listSupportResources()
  assert.equal(supportResources.length, 4)
  assert.ok(supportResources.some((item) => item.title.includes('荣基金')))
  assert.ok(supportResources.some((item) => item.regionCode === '上海'))
  assert.equal(store.db.prepare('SELECT COUNT(*) AS count FROM schema_migration').get().count, 10)
  const frozenAssessmentFks = store.db.prepare('PRAGMA foreign_key_list(match_assessment_v2)').all()
  assert.equal(frozenAssessmentFks.some((foreignKey) => foreignKey.table === 'trial_record'), false)
  assert.ok(store.db.prepare('PRAGMA table_info(trial_local_bookmark)').all().some((column) => column.name === 'match_assessment_id'))
  store.close()
})
